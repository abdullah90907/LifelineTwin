const {chromium}=require(process.env.LIFELINETWIN_PLAYWRIGHT || 'playwright');
const fs=require('node:fs');
const path=require('node:path');
(async()=>{
 const browser=await chromium.launch({channel:'msedge',headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const evidence=path.resolve('evidence/houston-showcase');fs.mkdirSync(evidence,{recursive:true});
 try {
  await page.goto('http://127.0.0.1:5173/',{waitUntil:'domcontentloaded'});
  await page.getByRole('heading',{name:/Houston Texas Medical Center access/}).waitFor();
  await page.waitForFunction(()=>document.querySelector('[data-renderer]')?.getAttribute('data-renderer')!=='initializing');
  const atlas=await (await page.request.get('http://127.0.0.1:5173/data/active-atlas.json')).json();
  const road=atlas.road_features.find(r=>r.name&&['primary','secondary','tertiary'].includes(r.kind));
  await page.getByLabel('Find a road to test').fill(road.name);
  await page.getByRole('button').filter({hasText:`${road.u} ↔ ${road.v}`}).first().click();
  await page.getByText('1/6 selected roads',{exact:true}).waitFor();
  const response=page.waitForResponse(r=>r.url().endsWith('/analysis/geographic')&&r.request().method()==='POST');
  await page.getByRole('button',{name:'Analyze disruption'}).click();
  const result=await (await response).json();
  if(result.analysis.closures.length!==1||result.analysis.closures[0].u!==road.u)throw Error('Manual road selection did not reach analysis');
  await page.getByText('Hypothetical disruption',{exact:true}).waitFor();
  await page.screenshot({path:path.join(evidence,'manual-selection.png'),fullPage:true});
  await page.getByRole('button',{name:'Clear selected roads',exact:true}).click();
  const automatic=page.waitForResponse(r=>r.url().endsWith('/analysis/geographic')&&r.request().method()==='POST',{timeout:120000});
  await page.getByRole('button',{name:'Analyze disruption'}).click();
  const impact=await (await automatic).json();
  if(!impact.analysis)throw Error(JSON.stringify(impact));
  fs.writeFileSync(path.join(evidence,'scenario.json'),JSON.stringify(impact,null,2));
  await page.getByText('Hypothetical disruption',{exact:true}).waitFor();
  await page.screenshot({path:path.join(evidence,'desktop.png'),fullPage:true});
  await page.getByLabel('Investigation title').fill('Texas Medical Center access disruption');
  await page.getByRole('button',{name:'Create saved investigation'}).click();
  await page.waitForURL('**/investigations/**',{timeout:120000});
  await page.getByRole('heading',{name:'Texas Medical Center access disruption',exact:true}).waitFor();
  await page.screenshot({path:path.join(evidence,'saved-investigation.png'),fullPage:true});
  const saved=await (await page.request.get('http://127.0.0.1:5173/api/investigations/'+page.url().split('/').at(-1))).json();
  if(saved.status!=='completed')throw Error('Investigation did not complete');
  fs.writeFileSync(path.join(evidence,'saved-investigation.json'),JSON.stringify(saved,null,2));
  await page.getByRole('link',{name:'Environmental evidence',exact:true}).click();
  await page.getByRole('heading',{name:'Next 12 hours'}).waitFor({timeout:40000});
  await page.screenshot({path:path.join(evidence,'weather.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:path.join(evidence,'weather-mobile.png'),fullPage:true});
  const summary={nodes:atlas.manifest.nodes,edges:atlas.manifest.directed_edges,hospitals:atlas.facilities.length,origins:atlas.origins.length,selected_road:road.name,manual_analysis:'passed',affected_origins:impact.analysis.changes.filter(r=>r.newly_disconnected||r.increase_m>0),saved_investigation:saved.id,forecast_points:saved.result.environment.forecast.forecast_values.length,page_errors:errors};
  fs.writeFileSync(path.join(evidence,'browser-verification.json'),JSON.stringify(summary,null,2));
  console.log(JSON.stringify(summary));
  if(errors.length)process.exitCode=1;
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1});
